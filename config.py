# ---------------------------------------------------------------- hash config
# CONFIG_HASH (§1.2c, S1-A): sha256-16 atas TOKENS + versi + policy inti.
# Dicatat di manifest sensus + snapshot; replay historis tidak berubah
# diam-diam bila universe/config berubah.
def _config_hash():
    payload = {
        "tokens": TOKENS,
        "universe_version": UNIVERSE_VERSION,
        "schema_version": SCHEMA_VERSION,
        "methodology_version": METHODOLOGY_VERSION,
        "policy_version": POLICY_VERSION,
        "policy": {
            "DEV_WATCH_PCT": DEV_WATCH_PCT,
            "DEV_ABSTAIN_PCT": DEV_ABSTAIN_PCT,
            "MIN_INDEPENDENT_POOLS": MIN_INDEPENDENT_POOLS,
            "MIN_INDEPENDENT_VENUES": MIN_INDEPENDENT_VENUES,
        },
    }
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True, default=str).encode("utf-8")
    ).hexdigest()[:16]


CONFIG_HASH = _config_hash()
